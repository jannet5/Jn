#!/usr/bin/env python3
"""Applies one of the brand concepts (docs/marka/konsept-N-belirtecler.json) to the Android app.

    python3 tools/apply_brand.py 2

Writes, and nothing else:
  app/src/main/kotlin/com/sende/app/ui/theme/BrandTokens.kt   colours (light + dark), shapes, motion
  app/src/main/kotlin/com/sende/app/ui/theme/BrandFontFamilies.kt   the bundled font families
  app/src/main/res/font/*.ttf                                  Latin + Latin Extended subsets of the fonts
  app/src/main/res/values/colors.xml, values-night/colors.xml  window / splash / launcher colours
  app/src/main/res/drawable/ic_launcher_foreground.xml, ic_launcher_monochrome.xml
  app/src/main/res/mipmap-anydpi-v26/ic_launcher*.xml

The JSON is the single source of truth: switching concept means running this with another number.
`koyuRenkler` (optional) is the dark palette; a concept without it is used as-is in both modes.
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIRS = [Path.home() / ".fonts", ROOT / "docs" / "marka" / "yazi"]
MAIN = ROOT / "app/src/main"
THEME_DIR = MAIN / "kotlin/com/sende/app/ui/theme"

# Latin, Latin-1, Latin Extended-A (Turkish ğ ş ı İ ö ç ü, French œ), common punctuation and arrows.
SUBSET_UNICODES = "U+0020-007E,U+00A0-017F,U+0218-021B,U+02C6,U+02DA,U+02DC,U+2010-2027,U+2030-203A,U+20AC,U+2122,U+2190-2193,U+2212,U+2215"

FONT_FILES = {
    "Bricolage Grotesque": "BricolageGrotesque[opsz,wdth,wght].ttf",
    "DM Sans": "DMSans[opsz,wght].ttf",
    "Manrope": "Manrope[wght].ttf",
    "Inter": "Inter[opsz,wght].ttf",
    "Space Grotesk": "SpaceGrotesk[wght].ttf",
    "Fraunces": "Fraunces[SOFT,WONK,opsz,wght].ttf",
    "Instrument Sans": "InstrumentSans[wdth,wght].ttf",
    "Sora": "Sora[wght].ttf",
}


def kotlin_color(hex_value: str) -> str:
    return "Color(0xFF" + hex_value.lstrip("#").upper() + ")"


def colors_block(name: str, palette: dict, dark: bool) -> str:
    keys = ["arkaplan", "yuzey", "yuzeyYuksek", "cizgi", "metin", "metinIkincil", "vurgu", "vurguUstu", "tehlike", "basari"]
    names = ["background", "surface", "surfaceHigh", "line", "text", "textSecondary", "accent", "onAccent", "danger", "success"]
    lines = [f"    val {name} = BrandColors("]
    for key, field in zip(keys, names):
        lines.append(f"        {field} = {kotlin_color(palette[key])},")
    lines.append(f"        isDark = {'true' if dark else 'false'},")
    lines.append("    )")
    return "\n".join(lines)


def write_tokens(data: dict, number: int) -> None:
    light = data["renkler"]
    dark_palette = data.get("koyuRenkler")
    base_is_dark = bool(data.get("karanlikMi"))
    corner = data["kose"]
    motion = data["hareket"]
    first = colors_block("light" if not base_is_dark else "dark", light, base_is_dark)
    if dark_palette:
        second = colors_block("dark", dark_palette, True)
        body = first + "\n\n" + second
    elif base_is_dark:
        body = first + "\n\n    val light = dark"
    else:
        body = first + "\n\n    val dark = light"
    text = f'''package com.sende.app.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/**
 * GENERATED by tools/apply_brand.py from docs/marka/konsept-{number}-belirtecler.json.
 * Do not edit by hand; run the script with another concept number to change the brand.
 */
object Brand {{
{body}

    val shapes = BrandShapes(card = {corner["kart"]}.dp, bubble = {corner["balon"]}.dp, button = {corner["dugme"]}.dp)

    val motion = BrandMotion(
        expandMillis = {motion["genislemeMs"]},
        dismissMillis = {motion["kaybolmaMs"]},
        springDamping = {motion["yayDamping"]}f,
        springStiffness = {float(motion["yaySertlik"])}f,
    )
}}
'''
    (THEME_DIR / "BrandTokens.kt").write_text(text, encoding="utf-8")


def find_font(family: str) -> Path:
    name = FONT_FILES.get(family)
    if name is None:
        sys.exit(f"font '{family}' is not in FONT_FILES; add its file name first")
    for directory in FONT_DIRS:
        candidate = directory / name
        if candidate.exists():
            return candidate
    sys.exit(f"font file {name} not found in {FONT_DIRS}")


def resource_name(family: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", family.lower()).strip("_")


def build_font(family: str) -> str:
    source = find_font(family)
    target_dir = MAIN / "res/font"
    target_dir.mkdir(parents=True, exist_ok=True)
    name = resource_name(family)
    target = target_dir / f"{name}.ttf"
    subprocess.run(
        [sys.executable, "-m", "fontTools.subset", str(source), f"--unicodes={SUBSET_UNICODES}",
         "--layout-features=*", "--no-hinting", "--desubroutinize", f"--output-file={target}"],
        check=True,
    )
    return name


def write_fonts(data: dict) -> None:
    typography = data["tipografi"]
    heading = build_font(typography["baslik"])
    body = build_font(typography["govde"])
    for old in (MAIN / "res/font").glob("*.ttf"):
        if old.stem not in (heading, body):
            old.unlink()

    def family(var: str, res: str, weights: list) -> str:
        entries = "\n".join(
            f"        Font(R.font.{res}, FontWeight.W{w}, variationSettings = FontVariation.Settings(FontVariation.weight({w}))),"
            for w in weights
        )
        return f"    val {var}: FontFamily = FontFamily(\n{entries}\n    )"

    text = f'''package com.sende.app.ui.theme

import androidx.compose.ui.text.ExperimentalTextApi
import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontVariation
import androidx.compose.ui.text.font.FontWeight
import com.sende.app.R

/**
 * GENERATED by tools/apply_brand.py. Variable fonts bundled in res/font (Latin + Latin Extended
 * subsets, SIL OFL); Arabic and other scripts fall back to the system fonts.
 */
@OptIn(ExperimentalTextApi::class)
object BrandFontFamilies {{
{family("heading", heading, [500, 600, 700])}

{family("body", body, [400, 500, 600])}
}}
'''
    (THEME_DIR / "BrandFontFamilies.kt").write_text(text, encoding="utf-8")


def svg_paths(svg_file: Path) -> list:
    svg = svg_file.read_text(encoding="utf-8")
    if re.search(r"<(rect|circle|ellipse|polygon|polyline|line|g|use)\b", svg):
        sys.exit(f"{svg_file.name}: only <path> icons are supported")
    paths = []
    for element in re.findall(r"<path\b[^>]*>", svg):
        d = re.search(r'\bd="([^"]+)"', element)
        fill = re.search(r'\bfill="(#[0-9A-Fa-f]{6})"', element)
        if not d or not fill:
            sys.exit(f"{svg_file.name}: every path needs d and a hex fill")
        paths.append((fill.group(1).upper(), re.sub(r"\s+", " ", d.group(1)).strip()))
    if not paths:
        sys.exit(f"{svg_file.name}: no paths")
    return paths


def vector_xml(paths: list, override_color: str = None) -> str:
    body = "\n".join(
        f'    <path\n        android:fillColor="{override_color or fill}"\n        android:pathData="{d}" />'
        for fill, d in paths
    )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/apply_brand.py from docs/marka. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''


def write_icons(data: dict, number: int) -> None:
    marka = ROOT / "docs/marka"
    res = MAIN / "res"
    (res / "drawable/ic_launcher_foreground.xml").write_text(vector_xml(svg_paths(marka / f"konsept-{number}-ikon-on.svg")), encoding="utf-8")
    (res / "drawable/ic_launcher_monochrome.xml").write_text(
        vector_xml(svg_paths(marka / f"konsept-{number}-ikon-mono.svg"), override_color="#FFFFFF"), encoding="utf-8")
    background = data["renkler"]["ikonArkaplan"].upper()
    (res / "drawable/ic_launcher_background.xml").write_text(
        f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/apply_brand.py: the plain brand colour behind the mark. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="{background}" />
</shape>
''', encoding="utf-8")
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (res / "mipmap-anydpi-v26" / name).write_text(adaptive, encoding="utf-8")


def write_window_colors(data: dict) -> None:
    light = data["renkler"]
    dark = data.get("koyuRenkler")
    day = light["arkaplan"]
    night = (dark or light)["arkaplan"]

    def xml(value: str) -> str:
        return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/apply_brand.py: window and splash background. -->
<resources>
    <color name="sende_background">{value.upper()}</color>
</resources>
'''

    (MAIN / "res/values/colors.xml").write_text(xml(day), encoding="utf-8")
    night_dir = MAIN / "res/values-night"
    night_dir.mkdir(exist_ok=True)
    (night_dir / "colors.xml").write_text(xml(night), encoding="utf-8")


def main() -> None:
    if len(sys.argv) != 2 or not sys.argv[1].isdigit():
        sys.exit(__doc__)
    number = int(sys.argv[1])
    data = json.loads((ROOT / f"docs/marka/konsept-{number}-belirtecler.json").read_text(encoding="utf-8"))
    write_tokens(data, number)
    write_fonts(data)
    write_icons(data, number)
    write_window_colors(data)
    print(f"concept {number} applied: {data['tipografi']['baslik']} + {data['tipografi']['govde']}")


if __name__ == "__main__":
    main()
